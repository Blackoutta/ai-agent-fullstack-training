import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { api } from '../src/api'
import BenchmarkView from '../src/views/BenchmarkView.vue'
import StrategiesView from '../src/views/StrategiesView.vue'
import ExperimentsView from '../src/views/ExperimentsView.vue'
import CompareView from '../src/views/CompareView.vue'
import { setup, task, strategy } from './fixtures'
afterEach(() => vi.restoreAllMocks())

describe('可操作的评测工作流', () => {
  it('编辑响应式任务并保存，不更改已有快照', async () => {
    const ctx = setup()
    vi.spyOn(api, 'state').mockResolvedValue(ctx.workspace.state.value!)
    const save = vi.spyOn(api, 'saveTask').mockResolvedValue(task)
    const wrapper = mount(BenchmarkView, { global: ctx.global })
    await wrapper.findAll('button').find(b => b.text() === '编辑')!.trigger('click')
    await wrapper.find('[role="dialog"] input').setValue('新任务名称')
    await wrapper.find('[role="dialog"] form').trigger('submit')
    await flushPromises()
    expect(save).toHaveBeenCalledWith(expect.objectContaining({ name: '新任务名称', id: 't1' }))
    expect(ctx.workspace.state.value!.runs[0]?.task?.name).toBe(task.name)
    expect(wrapper.find('[role="dialog"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('拒绝损坏的 JSON 导入并展示可读错误', async () => {
    const ctx = setup()
    const importer = vi.spyOn(api, 'importTasks')
    const wrapper = mount(BenchmarkView, { global: ctx.global })
    await wrapper.findAll('button').find(b => b.text().includes('导入 JSON'))!.trigger('click')
    await wrapper.find('textarea').setValue('{"tasks": [{"name":"不完整"}]}')
    await wrapper.find('form').trigger('submit')
    expect(wrapper.text()).toContain('每个任务需要')
    expect(importer).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('正确保存策略空价格为 null，并编辑 Vue proxy', async () => {
    const ctx = setup()
    vi.spyOn(api, 'state').mockResolvedValue(ctx.workspace.state.value!)
    const save = vi.spyOn(api, 'saveStrategy').mockResolvedValue(strategy)
    const wrapper = mount(StrategiesView, { global: ctx.global })
    await wrapper.findAll('button').find(b => b.text().includes('编辑配置'))!.trigger('click')
    await wrapper.find('form').trigger('submit')
    await flushPromises()
    expect(save).toHaveBeenCalledWith(expect.objectContaining({ input_price: null, output_price: null, api_key_env: 'TEST_KEY' }))
    wrapper.unmount()
  })
  it('任务 × 策略 × 次数计算预算并启动离线实验', async () => {
    const ctx = setup()
    vi.spyOn(api, 'state').mockResolvedValue(ctx.workspace.state.value!)
    const launch = vi.spyOn(api, 'experiment').mockResolvedValue(ctx.workspace.state.value!.experiments[0]!)
    const wrapper = mount(ExperimentsView, { global: ctx.global })
    await wrapper.find('input:not([type])').setValue('新实验')
    for (const box of wrapper.findAll('input[type="checkbox"]')) await box.setValue(true)
    await wrapper.find('input[type="number"]').setValue(2)
    expect(wrapper.find('.run-estimate').text()).toContain('4')
    await wrapper.find('form').trigger('submit')
    await flushPromises()
    expect(launch).toHaveBeenCalledWith(expect.objectContaining({ name: '新实验', mode: 'offline', trials: 2, task_ids: ['t1'], strategy_ids: ['s1', 's2'] }))
    wrapper.unmount()
  })
  it('取消需确认，调用真实取消 API', async () => {
    const ctx = setup()
    vi.spyOn(api, 'state').mockResolvedValue(ctx.workspace.state.value!)
    const cancel = vi.spyOn(api, 'cancel').mockResolvedValue(ctx.workspace.state.value!.experiments[0]!)
    const wrapper = mount(ExperimentsView, { global: ctx.global })
    await wrapper.findAll('button').find(b => b.text().includes('取消实验'))!.trigger('click')
    expect(cancel).not.toHaveBeenCalled()
    await wrapper.find('[role="dialog"] .destructive').trigger('click')
    await flushPromises()
    expect(cancel).toHaveBeenCalledWith('e1')
    wrapper.unmount()
  })
  it('离线回归结果强制暂缓，改条件清除旧报告', async () => {
    const ctx = setup()
    vi.spyOn(api, 'state').mockResolvedValue(ctx.workspace.state.value!)
    vi.spyOn(api, 'compare').mockResolvedValue({ baseline: 's1', candidate: 's2', gate: 'adopt', rows: [{ task_id: 't1', task_name: task.name, trial: 1, before: 'fail', after: 'pass', change: 'improved' }], summary: { improved: 1 }, note: '离线验证' })
    const wrapper = mount(CompareView, { global: ctx.global })
    await wrapper.findAll('select')[0]!.setValue('e1')
    await wrapper.findAll('select')[1]!.setValue('s1')
    await wrapper.findAll('select')[2]!.setValue('s2')
    await wrapper.find('form').trigger('submit')
    await flushPromises()
    expect(wrapper.text()).toContain('暂缓采用')
    await wrapper.findAll('select')[1]!.setValue('s2')
    expect(wrapper.text()).not.toContain('门禁原始依据')
    wrapper.unmount()
  })
})
